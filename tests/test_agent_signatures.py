"""PreToolUse hook: scripts/agent-signatures.py (D21), in a temporary project laid out like one that applied the workflow,
run the way Claude Code runs a hook: the event JSON on stdin; exit 0 lets the tool run, exit 2 blocks it with the reason on
stderr. Every case that expects a block checks the reason, not only the exit code."""
import json
import shutil
import tempfile
import unittest
from pathlib import Path

from test_hooks import ROOT, Project

SCRIPT = "agent-signatures.py"
FOOTER = "Fix the bug.\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)\n"
SESSION = "https://claude.ai/code/session_01AbCdEf"


class SigProject(Project):
    def __init__(self, tmp, config=None):
        super().__init__(tmp, config=config, hooks=())
        self.scripts = self.work / ".claude" / "gw" / "scripts"
        shutil.copy2(ROOT / "scripts" / SCRIPT, self.scripts / SCRIPT)

    def hook(self, event=None, raw=None):
        stdin = raw if raw is not None else json.dumps(dict({"hook_event_name": "PreToolUse", "cwd": str(self.work)}, **event))
        return self.run("python3", str(self.scripts / SCRIPT), stdin=stdin)

    def mcp(self, tool, **tool_input):
        return self.hook({"tool_name": f"mcp__github__{tool}", "tool_input": tool_input})

    def bash(self, command):
        return self.hook({"tool_name": "Bash", "tool_input": {"command": command}})


class Base(unittest.TestCase):
    config = {"agentSignatures": False}

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="gw-firmas-")).resolve()
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.p = SigProject(self.tmp, self.config)

    def blocked(self, result, *texts):
        code, out = result
        self.assertEqual(code, 2, out)
        for t in texts:
            self.assertIn(t, out)

    def allowed(self, result):
        code, out = result
        self.assertEqual((code, out.strip()), (0, ""), out)


class GithubTools(Base):
    def test_every_publishing_tool_blocks_a_signed_body(self):
        for tool in ("create_pull_request", "update_pull_request", "add_issue_comment", "update_issue_comment",
                     "issue_write", "add_reply_to_pull_request_comment", "add_comment_to_pending_review",
                     "pull_request_review_write"):
            with self.subTest(tool=tool):
                self.blocked(self.p.mcp(tool, body=FOOTER), "the body carries an agent signature", "Generated with",
                             "agentSignatures: false", "run the call again")

    def test_signature_in_the_title_blocks(self):
        self.blocked(self.p.mcp("create_pull_request", title="\U0001F916 Generated with [Claude Code]", body="ok"), "the title carries")

    def test_each_signature_kind_blocks_and_case_is_ignored(self):
        for text in ("CO-AUTHORED-BY: Claude Opus <noreply@anthropic.com>", "Co-Authored-By: Claude Code <x@y.z>",
                     "claude-session: abc", "generated by [claude code]", SESSION, f"<{SESSION}>"):
            with self.subTest(text=text):
                self.blocked(self.p.mcp("add_issue_comment", body=f"Hi\n\n{text}"), "agent signature")

    def test_clean_text_and_human_coauthor_pass(self):
        self.allowed(self.p.mcp("create_pull_request", title="feat: x", body="Fixes it.\nCo-Authored-By: Claude Pérez <c@example.com>"))
        self.allowed(self.p.mcp("add_issue_comment", body="We drop the 'Generated with Claude Code' footer here"))

    def test_missing_or_non_string_fields_pass(self):
        self.allowed(self.p.mcp("create_pull_request", title="t"))
        self.allowed(self.p.mcp("add_issue_comment", body=None))
        self.allowed(self.p.hook({"tool_name": "mcp__github__add_issue_comment"}))
        self.allowed(self.p.hook({"tool_name": "mcp__github__add_issue_comment", "tool_input": "text"}))

    def test_unaffected_tools_pass_even_when_signed(self):
        self.allowed(self.p.mcp("create_or_update_file", content=FOOTER, message="docs: x"))
        self.allowed(self.p.mcp("push_files", files=[{"content": FOOTER}], message="docs: x"))
        self.allowed(self.p.mcp("get_file_contents", path=FOOTER))
        self.allowed(self.p.hook({"tool_name": "Write", "tool_input": {"content": FOOTER}}))
        self.allowed(self.p.hook({"tool_name": "mcp__other__add_issue_comment", "tool_input": {"body": FOOTER}}))
        self.allowed(self.p.hook({"tool_input": {"body": FOOTER}}))


class MoreTools(Base):
    def test_commit_message_fields_of_merge_and_file_tools_block(self):
        sig = "x\n\nClaude-Session: abc"
        for tool, field in (("merge_pull_request", "commit_message"), ("merge_pull_request", "commit_title"),
                            ("enable_pr_auto_merge", "commitBody"), ("enable_pr_auto_merge", "commitHeadline"),
                            ("push_files", "message"), ("create_or_update_file", "message")):
            with self.subTest(tool=tool, field=field):
                self.blocked(self.p.mcp(tool, **{field: sig}), f"the {field} carries an agent signature", "Claude-Session")

    def test_any_server_name_with_github_in_it_is_covered(self):
        for server in ("plugin_github_github", "my-github"):
            self.blocked(self.p.hook({"tool_name": f"mcp__{server}__add_issue_comment", "tool_input": {"body": FOOTER}}),
                         "agent signature")
        self.allowed(self.p.hook({"tool_name": "mcp__gitlab__add_issue_comment", "tool_input": {"body": FOOTER}}))

    def test_settings_matchers_agree_with_the_code(self):
        import re
        sys_path = Path(__file__).resolve().parent.parent
        for rel in (".claude/settings.json", "templates/claude/settings.json", "hooks/hooks.json"):
            data = json.loads((sys_path / rel).read_text())
            entry = [e for e in data["hooks"]["PreToolUse"] if "agent-signatures.py" in json.dumps(e)][0]
            for name in ("mcp__github__push_files", "mcp__plugin_github_github__merge_pull_request", "Bash"):
                self.assertTrue(re.search(entry["matcher"], name), (rel, name))
            self.assertFalse(re.search(entry["matcher"], "mcp__github__get_me"), rel)


class Anchoring(Base):
    QUOTED = ("Docs: the footer looks like this:\n\n```\n\U0001F916 Generated with [Claude Code]\n"
              "Co-Authored-By: Claude <noreply@anthropic.com>\n```\n\n"
              "    Claude-Session: abc\n    " + SESSION + "\n")

    def test_quotes_in_code_blocks_or_indented_pass_and_the_same_text_at_column_0_blocks(self):
        self.allowed(self.p.mcp("create_pull_request", title="docs: x", body=self.QUOTED))
        self.allowed(self.p.mcp("add_issue_comment", body="~~~\nClaude-Session: abc\n~~~"))
        self.allowed(self.p.mcp("add_issue_comment", body="see " + SESSION))
        for line in ("Co-Authored-By: Claude <noreply@anthropic.com>", "Claude-Session: abc", SESSION,
                     "\U0001F916 Generated with [Claude Code]"):
            with self.subTest(line=line):
                self.blocked(self.p.mcp("add_issue_comment", body="Quote:\n" + line), "agent signature", line)
        self.blocked(self.p.mcp("add_issue_comment", body="```\nok\n```\nClaude-Session: abc"), "Claude-Session")

    def test_gh_body_quoting_in_a_code_block_passes(self):
        self.allowed(self.p.bash("gh pr create --title t --body '" + self.QUOTED + "'"))


class MoreGh(Base):
    def test_stdin_body_file_scans_the_whole_command_and_does_not_need_a_file(self):
        heredoc = "gh pr create --title t --body-file - <<'EOF'\nFix.\n\nClaude-Session: abc\nEOF"
        self.blocked(self.p.bash(heredoc), "Claude-Session")
        self.blocked(self.p.bash(heredoc.replace("--body-file -", "-F -")), "Claude-Session")
        self.allowed(self.p.bash("gh pr create --title t --body-file - <<'EOF'\nFix.\nEOF"))
        self.allowed(self.p.bash("echo fine | gh pr create --body-file -"))

    def test_other_gh_commands_and_option_forms_block(self):
        sig = "x\n\nClaude-Session: abc"
        for cmd in (f"gh pr merge 3 --subject '{sig}'", f"gh pr merge 3 -b '{sig}'", f"gh pr merge 3 --body '{sig}'",
                    f"gh issue edit 3 --body '{sig}'", f"gh release create v1 --notes '{sig}'",
                    f"gh release edit v1 -n '{sig}'", f"gh pr create -b'{sig}'", f"gh pr create --title t -t'{sig}'",
                    f"gh api repos/o/r/issues/3/comments -f body='{sig}'",
                    f"gh api repos/o/r/pulls/3 --raw-field body='{sig}'", f"gh api x -F body='{sig}'",
                    f"gh api x --field body='{sig}'"):
            with self.subTest(cmd=cmd):
                self.blocked(self.p.bash(cmd), "agent signature", "Claude-Session")

    def test_notes_file_and_api_at_file_are_read(self):
        p = self.p
        (p.work / "n.md").write_text("x\nClaude-Session: abc\n")
        self.blocked(p.bash("gh release create v1 --notes-file n.md"), "--notes-file carries")
        self.blocked(p.bash("gh api x -F body=@n.md"), "carries")
        self.blocked(p.bash("gh api x -F body=@nope.md"), "cannot read the file nope.md")
        self.allowed(p.bash("gh api repos/o/r/issues -f title=ok -f body=fine"))
        self.allowed(p.bash("gh release list"))


